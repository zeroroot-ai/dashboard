#!/usr/bin/env node
/**
 * Build guard: verify that the committed TypeScript proto bindings under
 * `src/gen/` are in sync with the two source proto trees they are generated
 * from (the OSS SDK at `opensource/sdk/api/proto` and the gibson daemon-local
 * tree at `enterprise/platform/gibson/internal/server/daemon/api`).
 *
 * Sister gates: `check-authz-registry-fresh.mjs` (src/gen/authz/registry.ts)
 * and `check-mission-schema-fresh.mjs` (the SDK mission schema). This one
 * closes the remaining hole: nothing guarded `src/gen/**\/*_pb.ts`, so wire
 * drift accumulated silently until somebody regenerated and found a
 * thousand-line diff unrelated to their change. See dashboard#1014.
 *
 * Two modes, chosen automatically
 * -------------------------------
 *
 * FULL (both proto trees present, i.e. a polyrepo workstation):
 *   Regenerates the whole binding tree into a scratch directory via
 *   `proto-generate.mjs --out=<tmp>` and byte-diffs every produced file
 *   against its committed counterpart. Any missing or differing file fails.
 *
 * STRUCTURAL (a proto tree is absent, i.e. dashboard-only CI or the Docker
 * build, neither of which clones the siblings):
 *   Cannot regenerate, so instead it proves the committed tree is actually
 *   *there*: it walks the import closure rooted at every `@/src/gen/...`
 *   import in the app sources and requires each resolved module to exist, be
 *   non-empty, and carry the `@generated by protoc-gen-es` header. This is
 *   what stops the classic vacuity hole where a gate "passes" against an
 *   empty or deleted `src/gen/`.
 *
 * The structural pass runs in FULL mode too, before the diff.
 *
 * There is no `--skip` / `--permissive` env escape. Drift fails the build,
 * period. (Same stance as check-mission-schema-fresh.mjs.)
 *
 * Usage
 *   node scripts/check-proto-bindings-fresh.mjs
 *   node scripts/check-proto-bindings-fresh.mjs --selftest
 *
 * Resolution
 *   Run `pnpm proto:generate` and commit the regenerated `src/gen/` files
 *   alongside the proto change.
 *
 * Fixes: zeroroot-ai/dashboard#1014
 */

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
  mkdirSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_NAME = "check-proto-bindings-fresh.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const DASHBOARD_ROOT = resolve(__dirname, "..");
const GEN_ROOT = resolve(DASHBOARD_ROOT, "src/gen");
const GENERATOR = resolve(__dirname, "proto-generate.mjs");

/** Header every protoc-gen-es output starts with. */
const GENERATED_MARKER = "@generated by protoc-gen-es";

/**
 * Source roots scanned for `@/src/gen/...` imports. `scripts/` is excluded on
 * purpose: it holds AST-check fixtures that import deliberately-illegal
 * modules which do not exist on disk.
 */
const SOURCE_ROOTS = ["app", "components", "hooks", "lib", "src", "e2e"];

/**
 * Committed files under src/gen/ that this generator does not produce and
 * that therefore must not be diffed:
 *
 *   authz/registry.ts  emitted by gen-authz-registry.mjs, guarded by
 *                      check-authz-registry-fresh.mjs.
 */
const NOT_PROTO_GENERATED = new Set(["authz/registry.ts"]);

/**
 * Monotonic-shrink baseline of drift that predates this gate.
 *
 * Same idiom as `.color-allowlist.json` (see CLAUDE.md → "No hardcoded
 * colors"): it records the violations that existed the day the guard landed so
 * the guard can go live immediately, and it may only ever shrink.
 *
 * Entries are keyed by path under `src/gen/` and pinned to the **committed**
 * file's sha256, never the regenerated one — the regenerated bytes depend on
 * which commit of the sibling `sdk` / `gibson` checkouts you happen to have,
 * so pinning them would make the baseline fail differently on every machine.
 * The committed side is a property of this repo alone.
 *
 * Semantics:
 *   - stale file, in baseline, committed hash matches  → tolerated, warn.
 *   - stale file, not in baseline                      → FAIL. New drift.
 *   - stale file, in baseline, committed hash differs  → FAIL. The baselined
 *     content was replaced by something that is still stale; re-baselining is
 *     deliberately not automated.
 *   - baseline entry whose file is no longer stale     → FAIL, run --shrink.
 *   - missing file (generator emits it, repo lacks it) → FAIL, never tolerated.
 */
const BASELINE_FILE = resolve(DASHBOARD_ROOT, ".proto-bindings-baseline.json");

function sha256(text) {
  return createHash("sha256").update(text, "utf8").digest("hex");
}

function loadBaseline() {
  if (!existsSync(BASELINE_FILE)) return { entries: {} };
  let parsed;
  try {
    parsed = JSON.parse(readFileSync(BASELINE_FILE, "utf8"));
  } catch (err) {
    process.stderr.write(
      `[${SCRIPT_NAME}] FAIL, ${BASELINE_FILE} is not valid JSON: ${err.message}\n`,
    );
    process.exit(2);
  }
  if (!parsed || typeof parsed.entries !== "object" || parsed.entries === null) {
    process.stderr.write(
      `[${SCRIPT_NAME}] FAIL, ${BASELINE_FILE} must be an object with an "entries" map.\n`,
    );
    process.exit(2);
  }
  return parsed;
}

function writeBaseline(baseline) {
  writeFileSync(BASELINE_FILE, JSON.stringify(baseline, null, 2) + "\n", "utf8");
}

/**
 * Pure verdict function over a diff result plus the baseline. Extracted so the
 * selftest can drive every branch without a buf toolchain or sibling clones.
 *
 * @param {{missing: string[], stale: string[], committedHashes: Map<string,string>, baseline: {entries: Record<string, {committedSha256: string}>}}} input
 */
function classify({ missing, stale, committedHashes, baseline }) {
  const entries = baseline.entries ?? {};
  const staleSet = new Set(stale);
  const problems = [];
  const tolerated = [];

  for (const rel of stale) {
    const entry = entries[rel];
    if (!entry) {
      problems.push(
        `stale: src/gen/${rel} does not match the source protos, and is not in the baseline.`,
      );
      continue;
    }
    const actual = committedHashes.get(rel);
    if (entry.committedSha256 !== actual) {
      problems.push(
        `stale: src/gen/${rel} is still out of sync, but its committed content changed ` +
          `since it was baselined (baseline ${String(entry.committedSha256).slice(0, 12)}…, ` +
          `now ${String(actual).slice(0, 12)}…). Regenerate it rather than re-baselining.`,
      );
      continue;
    }
    tolerated.push(rel);
  }

  for (const rel of missing) {
    problems.push(
      `missing: src/gen/${rel} is produced by the generator but absent from the repo. ` +
        `Never baselined.`,
    );
  }

  const obsolete = Object.keys(entries)
    .filter((rel) => !staleSet.has(rel))
    .sort();
  if (obsolete.length > 0) {
    problems.push(
      `${obsolete.length} baseline entr(ies) no longer describe stale files: ` +
        `${obsolete.join(", ")}. Run ` +
        `\`node scripts/check-proto-bindings-fresh.mjs --shrink\` and commit the result.`,
    );
  }

  const shrunkEntries = { ...entries };
  for (const rel of obsolete) delete shrunkEntries[rel];

  return {
    problems,
    tolerated: tolerated.sort(),
    obsolete,
    shrunkBaseline: { ...baseline, entries: shrunkEntries },
  };
}

function fail(lines) {
  process.stderr.write(`\n[${SCRIPT_NAME}] FAIL\n`);
  for (const l of lines) process.stderr.write(`  ${l}\n`);
  process.stderr.write("\nResolve by running: pnpm proto:generate\n");
  process.stderr.write(
    "Then commit the regenerated src/gen/ files alongside the proto change.\n",
  );
  process.exit(1);
}

// --------------------------------------------------------------------------
// import-closure discovery
// --------------------------------------------------------------------------

const FROM_RE = /\bfrom\s*["']([^"']+)["']/g;
const DYNAMIC_IMPORT_RE = /\bimport\(\s*["']([^"']+)["']\s*\)/g;

function specifiersIn(text) {
  const out = [];
  for (const re of [FROM_RE, DYNAMIC_IMPORT_RE]) {
    re.lastIndex = 0;
    let m;
    while ((m = re.exec(text)) !== null) out.push(m[1]);
  }
  return out;
}

function* walkFiles(dir, exts) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const e of entries) {
    const p = join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name === "node_modules" || e.name === ".next") continue;
      yield* walkFiles(p, exts);
    } else if (exts.some((x) => e.name.endsWith(x))) {
      yield p;
    }
  }
}

/**
 * Every `src/gen/...` module imported from the app sources, as a repo-relative
 * path with no extension (e.g. "src/gen/gibson/daemon/v1/daemon_pb").
 *
 * Both alias spellings resolve to the same tree via tsconfig `paths`:
 *   "@/src/gen/..."  →  <root>/src/gen/...   (via "@/src/*")
 *   "@/gen/..."      →  <root>/gen/...       (via "@/*", legacy spelling)
 * The second form is normalised into src/gen/ as well; it only appears in
 * excluded fixture files today, but normalising costs nothing.
 */
function discoverEntryModules(root) {
  const genRoot = resolve(root, "src/gen");
  const found = new Set();
  for (const sub of SOURCE_ROOTS) {
    const dir = join(root, sub);
    for (const file of walkFiles(dir, [".ts", ".tsx", ".mts", ".js", ".jsx"])) {
      // Never treat the generated tree itself as an entry point; its internal
      // relative imports are followed by the closure walk instead.
      if (file.startsWith(genRoot + "/")) continue;
      for (const spec of specifiersIn(readFileSync(file, "utf8"))) {
        const m = /^@\/(?:src\/)?gen\/(.+)$/.exec(spec);
        if (m) found.add(`src/gen/${m[1]}`);
      }
    }
  }
  return [...found].sort();
}

/** Resolve a repo-relative extension-less module path to an on-disk file. */
function resolveModuleFile(root, relNoExt) {
  for (const ext of [".ts", ".tsx", ".d.ts"]) {
    const p = resolve(root, relNoExt + ext);
    if (existsSync(p) && statSync(p).isFile()) return p;
  }
  const idx = resolve(root, relNoExt, "index.ts");
  if (existsSync(idx)) return idx;
  return null;
}

/**
 * Structural pass. Proves the committed src/gen/ tree is populated and
 * generator-produced, using only what is on disk. Returns nothing; calls
 * fail() on any problem.
 */
function structuralCheck(root) {
  const genRoot = resolve(root, "src/gen");
  const entries = discoverEntryModules(root);

  // Guard the guard: if the scanner finds nothing it is broken (or the source
  // roots moved), and every subsequent assertion would be vacuously true.
  if (entries.length === 0) {
    fail([
      `no "@/src/gen/..." imports found under ${SOURCE_ROOTS.join(", ")}.`,
      "The scanner found nothing to verify, which means it is broken or the",
      "source layout moved. Refusing to pass vacuously.",
    ]);
  }

  const problems = [];
  const seen = new Set();
  const queue = [...entries.map((e) => ({ mod: e, via: "<source import>" }))];

  while (queue.length > 0) {
    const { mod, via } = queue.pop();
    if (seen.has(mod)) continue;
    seen.add(mod);

    const file = resolveModuleFile(root, mod);
    if (!file) {
      problems.push(`missing binding: ${mod}(.ts) — imported by ${via}`);
      continue;
    }
    const text = readFileSync(file, "utf8");
    if (text.trim().length === 0) {
      problems.push(`empty binding: ${mod}.ts`);
      continue;
    }
    const rel = relative(genRoot, file);
    if (file.endsWith("_pb.ts") && !text.includes(GENERATED_MARKER)) {
      problems.push(
        `hand-edited or non-generated binding: src/gen/${rel} is missing the ` +
          `"${GENERATED_MARKER}" header.`,
      );
      continue;
    }

    // Follow relative imports that stay inside src/gen/.
    for (const spec of specifiersIn(text)) {
      if (!spec.startsWith(".")) continue;
      const target = resolve(dirname(file), spec);
      if (!target.startsWith(genRoot + "/")) continue;
      queue.push({
        mod: relative(root, target),
        via: `src/gen/${rel}`,
      });
    }
  }

  if (problems.length > 0) {
    fail([
      `${problems.length} problem(s) in the committed src/gen/ tree:`,
      ...problems,
    ]);
  }

  process.stdout.write(
    `[${SCRIPT_NAME}] structural OK, ${seen.size} binding module(s) reachable ` +
      `from ${entries.length} source import(s)\n`,
  );
}

