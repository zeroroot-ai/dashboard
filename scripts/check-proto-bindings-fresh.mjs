function probeSources() {
  try {
    return JSON.parse(
      execFileSync("node", [GENERATOR, "--probe"], {
        encoding: "utf8",
        maxBuffer: 4 * 1024 * 1024,
      }),
    );
  } catch (err) {
    process.stderr.write(
      `[${SCRIPT_NAME}] FAIL, could not probe the proto source trees: ${err.message}\n`,
    );
    process.exit(2);
  }
}

function listRelFiles(dir, prefix = "") {
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${e.name}` : e.name;
    if (e.isDirectory()) out.push(...listRelFiles(join(dir, e.name), rel));
    else out.push(rel);
  }
  return out;
}

function fullCheck() {
  const scratch = mkdtempSync(join(tmpdir(), "dashboard-proto-fresh-"));
  const expectedRoot = join(scratch, "gen");
  try {
    execFileSync("node", [GENERATOR, `--out=${expectedRoot}`], {
      encoding: "utf8",
      stdio: "inherit",
      maxBuffer: 64 * 1024 * 1024,
    });
  } catch (err) {
    rmSync(scratch, { recursive: true, force: true });
    process.stderr.write(
      `[${SCRIPT_NAME}] FAIL, generator errored: ${err.message}\n`,
    );
    process.exit(2);
  }

  try {
    const expectedFiles = listRelFiles(expectedRoot).sort();
    if (expectedFiles.length === 0) {
      fail([
        `the generator produced no files into ${expectedRoot}.`,
        "That is a generator bug, not a drift result. Refusing to pass.",
      ]);
    }

    const missing = [];
    const stale = [];
    const committedHashes = new Map();
    for (const rel of expectedFiles) {
      if (NOT_PROTO_GENERATED.has(rel)) continue;
      const committedPath = join(GEN_ROOT, rel);
      if (!existsSync(committedPath)) {
        missing.push(rel);
        continue;
      }
      const a = readFileSync(committedPath, "utf8");
      const b = readFileSync(join(expectedRoot, rel), "utf8");
      if (a !== b) {
        stale.push(rel);
        committedHashes.set(rel, sha256(a));
      }
    }

    const baseline = loadBaseline();
    const verdict = classify({ missing, stale, committedHashes, baseline });

    if (shrinkMode) {
      writeBaseline(verdict.shrunkBaseline);
      process.stdout.write(
        `[${SCRIPT_NAME}] --shrink, removed ${verdict.obsolete.length} obsolete ` +
          `baseline entr(ies): ${verdict.obsolete.join(", ") || "(none)"}\n`,
      );
      process.stdout.write(
        `[${SCRIPT_NAME}] --shrink, ${Object.keys(verdict.shrunkBaseline.entries).length} ` +
          `entr(ies) remain. Commit ${relative(DASHBOARD_ROOT, BASELINE_FILE)}.\n`,
      );
      return;
    }

    if (verdict.problems.length > 0) {
      fail(verdict.problems);
    }

    if (verdict.tolerated.length > 0) {
      process.stdout.write(
        `[${SCRIPT_NAME}] note, ${verdict.tolerated.length} known-stale binding(s) ` +
          `tolerated by ${relative(DASHBOARD_ROOT, BASELINE_FILE)}: ` +
          `${verdict.tolerated.join(", ")}\n`,
      );
    }

    // Informational only. proto-generate.mjs rsyncs without --delete into
    // src/gen/, and some committed bindings (e.g. gibson/session/v1) are
    // deliberately excluded from the generated modules, so an "extra" file is
    // not automatically wrong. Surface them so an actually-orphaned binding
    // gets noticed at review time rather than never.
    const expectedSet = new Set(expectedFiles);
    const extras = listRelFiles(GEN_ROOT)
      .filter((f) => !expectedSet.has(f) && !NOT_PROTO_GENERATED.has(f))
      .sort();
    if (extras.length > 0) {
      process.stdout.write(
        `[${SCRIPT_NAME}] note, ${extras.length} committed file(s) under src/gen/ ` +
          `are not produced by proto-generate.mjs (expected for the deliberately ` +
          `excluded modules): ${extras.join(", ")}\n`,
      );
    }

    process.stdout.write(
      `[${SCRIPT_NAME}] OK, ${expectedFiles.length} generated binding file(s) ` +
        `match the source protos\n`,
    );
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

