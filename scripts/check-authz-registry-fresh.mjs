#!/usr/bin/env node
/**
 * Build guard: verify that the **committed** `src/gen/authz/registry.ts`
 * matches what `gen-authz-registry.mjs` produces from the SDK and gibson
 * daemon-local proto annotations.
 *
 * Until dashboard#1019 `prebuild` ran `gen-authz-registry.mjs` immediately
 * before this gate, so the gate diffed the file the generator had just written
 * against the generator, and could not fail. The generator no longer runs in
 * `prebuild`; regeneration is an explicit `pnpm gen:authz`.
 *
 * Mechanics, modes and the no-escape-hatch stance live in
 * `scripts/lib/freshness-gate.mjs`. The `SKIP_AUTHZ_REGISTRY_CHECK=1` escape
 * is gone: dashboard-only builds reach STRUCTURAL mode because
 * `gen-authz-registry.mjs --probe` reports the two proto trees absent, not
 * because they were told to look away.
 *
 * Usage
 *   node scripts/check-authz-registry-fresh.mjs
 *   node scripts/check-authz-registry-fresh.mjs --selftest
 *
 * Spec: dashboard-authz-ui-gating Requirement 1.4, 1.5, 9.5.
 * Sister-spec: cross-repo-cohesion-fixes Requirement 2.4, 2.5.
 * Fixes: zeroroot-ai/dashboard#1019
 */

import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { main } from "./lib/freshness-gate.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const DASHBOARD_ROOT = resolve(__dirname, "..");
const ARTIFACT = "src/gen/authz/registry.ts";

main(
  {
    scriptName: "check-authz-registry-fresh.mjs",
    artifact: ARTIFACT,
    generator: resolve(__dirname, "gen-authz-registry.mjs"),
    generatedMarker:
      "// Code generated by scripts/gen-authz-registry.mjs. DO NOT EDIT.",
    resolution: "pnpm gen:authz",
    maxBuffer: 64 * 1024 * 1024,
    sampleFrom: resolve(DASHBOARD_ROOT, ARTIFACT),
    syntheticSample:
      "// Code generated by scripts/gen-authz-registry.mjs. DO NOT EDIT.\n" +
      "export const AuthRegistry = {};\n",
  },
  process.argv.slice(2),
  DASHBOARD_ROOT,
);
